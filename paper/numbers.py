def printed(value, decimals):
    return f"{value:,.{decimals}f}".replace(",", "{,}")


def main():
    lines = ["% Generated by numbers.py from the number files in ../figures/."]
    for macro, (script, key, decimals, *factor) in ROWS.items():
        value = json.loads((FOLDER / f"{script}.json").read_text(encoding="utf-8"))
        for part in key.split("/"):
            value = value[part]
        value = value * factor[0] if factor else value
        lines.append(f"\\newcommand{{\\{macro}}}{{{printed(value, decimals)}}}")
    (HERE / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
